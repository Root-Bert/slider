/**
 * Builds the MCP App page for `show_presentation` (`view.ts`) into one HTML file and writes it as
 * a string module the API serves (`src/services/mcp-view-html.ts`) – the Docker image and the
 * desktop app copy `src` only, and the host's sandbox loads nothing from outside.
 *
 * A2UI needs zod 3, the repo overrides zod to 4 for every package (root `overrides`) – so the
 * renderer is installed apart, in a folder of its own outside the workspace, at fixed versions.
 *
 *   bun apps/api/mcp-view/build.ts
 */
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

const DEPENDENCIES = {
  '@a2ui/lit': '0.16.0',
  '@a2ui/web_core': '0.16.1',
  lit: '3.3.3',
};

const here = import.meta.dir;
const work = join(tmpdir(), 'slider-mcp-view');
mkdirSync(work, { recursive: true });
writeFileSync(
  join(work, 'package.json'),
  JSON.stringify({ name: 'slider-mcp-view', private: true, dependencies: DEPENDENCIES }, null, 2),
);
const install = Bun.spawnSync(['bun', 'install'], {
  cwd: work,
  stdout: 'inherit',
  stderr: 'inherit',
});
if (install.exitCode !== 0) process.exit(install.exitCode ?? 1);
copyFileSync(join(here, 'view.ts'), join(work, 'view.ts'));

const built = await Bun.build({
  entrypoints: [join(work, 'view.ts')],
  target: 'browser',
  format: 'esm',
  minify: true,
  // Lit's production build, not its dev mode.
  conditions: ['production'],
  define: { 'process.env.NODE_ENV': '"production"' },
});
if (!built.success) {
  for (const log of built.logs) console.error(log);
  process.exit(1);
}
const js = (await built.outputs[0]!.text()).replace(/<\/script/gi, '<\\/script');
const css = await Bun.file(join(here, 'view.css')).text();
// A classic script before the module: it sees errors while the module's imports load (A2UI
// throwing there would otherwise leave a blank frame) and tells the host the new height. The
// line it removes first stays where no script runs at all (a host's CSP without inline scripts).
const ERRORS = `(function () {
  document.getElementById('silent').remove();
  function say(text) {
    var line = document.createElement('p');
    line.style.cssText = 'margin:0;padding:8px 0;font-size:13px;color:#888';
    line.textContent = text;
    document.getElementById('root').append(line);
    var height = Math.ceil(document.documentElement.getBoundingClientRect().height);
    parent.postMessage({ jsonrpc: '2.0', method: 'ui/notifications/size-changed', params: { height: height } }, '*');
  }
  addEventListener('error', function (e) { say('Fehler: ' + e.message); });
  addEventListener('unhandledrejection', function (e) {
    say('Fehler: ' + ((e.reason && e.reason.message) || String(e.reason)));
  });
})();`;
const html = `<!doctype html>
<html lang="de">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>${css}</style>
</head>
<body>
<div id="root"><p id="silent" style="margin:0;padding:8px 0;font-size:13px;color:#888">In diesem Rahmen laufen keine Skripte.</p></div>
<script>${ERRORS}</script>
<script type="module">${js}</script>
</body>
</html>
`;
// Gzipped, base64: A2UI brings zod along, the page is ~500 KB as text.
const packed = gzipSync(html, { level: 9 }).toString('base64');
const out = join(here, '../src/services/mcp-view-html.ts');
writeFileSync(
  out,
  `// Generated by apps/api/mcp-view/build.ts – do not edit. The MCP App page of show_presentation, gzipped, base64.\n// prettier-ignore\nexport const MCP_VIEW_HTML_GZ =\n  '${packed}';\n`,
);
console.info(
  `${out}: ${(html.length / 1024).toFixed(0)} KB page, ${(packed.length / 1024).toFixed(0)} KB packed`,
);
