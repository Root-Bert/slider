/** Marks drawn with even-odd fill, as their sources are. */
const EVEN_ODD: ReadonlySet<IntegrationProvider> = new Set(['black-forest-labs']);

/** A service's mark, `size` px square. */
export function ProviderLogo({
  provider,
  size = 20,
  className,
}: {
  provider: IntegrationProvider;
  size?: number;
  className?: string;
}) {
  const mono = MONO[provider];
  const coloured = COLOURED[provider];
  if (mono || coloured) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        aria-hidden
        className={cn('shrink-0', className)}
      >
        {mono ? (
          <path
            d={mono}
            fill="currentColor"
            fillRule={EVEN_ODD.has(provider) ? 'evenodd' : undefined}
          />
        ) : (
          coloured!.map(([fill, d]) => <path key={d} d={d} fill={fill} />)
        )}
      </svg>
    );
  }
  // The server's own speech to text: stays on it. A service of one's own: no mark.
  return (
    <Icon
      name={provider === 'self-hosted' ? 'lock' : 'link'}
      size={size}
      className={cn('shrink-0', className)}
    />
  );
}
