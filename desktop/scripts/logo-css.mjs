// The start screen plays the web app's logo animations: this takes them out of its stylesheet
// (apps/web/src/styles/index.css) into generated/logo-animations.css – the animations, the
// `hop` keyframes, the easing curves they use and the logo colours of both themes, and their names
// (generated/logo-animations.js) – so there is
// one copy of them. Run by scripts/stage.mjs; on its own: node scripts/logo-css.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const desktop = fileURLToPath(new URL('..', import.meta.url));
const source = path.join(desktop, '../apps/web/src/styles/index.css');
const target = path.join(desktop, 'generated/logo-animations.css');
const names = path.join(desktop, 'generated/logo-animations.js');
const css = readFileSync(source, 'utf8');

const fail = (what) => {
  throw new Error(`logo-css: ${what} not found in ${source} – update scripts/logo-css.mjs`);
};
const between = (start, end) => {
  const from = css.indexOf(start);
  if (from < 0) fail(start);
  const to = css.indexOf(end, from);
  if (to < 0) fail(end);
  return css.slice(from, to).trimEnd();
};

const animations = between('/* ── Logo animations', '/*\n * Your own pointer');
const hop = css.match(/@keyframes hop \{[\s\S]*?\n {2}\}/)?.[0] ?? fail('@keyframes hop');
const tokens = (pattern, text) => [...text.matchAll(pattern)].map((match) => `  ${match[0]}`);
const curves = tokens(/--(ease-[a-z]+|animate-hop): [^;]+;/g, css);
const darkLogo = tokens(
  /--color-logo(-[a-z]+)?: [^;]+;/g,
  css.slice(0, css.indexOf('@theme') + 4000),
);
const lightBlock = between(":root[data-theme='light'] {", '\n}');
const lightLogo = tokens(/--color-logo(-[a-z]+)?: [^;]+;/g, lightBlock);
if (!curves.length || !darkLogo.length || !lightLogo.length) fail('easing or logo colour tokens');

const unique = (lines) => [...new Map(lines.map((line) => [line.split(':')[0], line])).values()];
mkdirSync(path.dirname(target), { recursive: true });
writeFileSync(
  target,
  `/* Generated by desktop/scripts/logo-css.mjs from apps/web/src/styles/index.css – do not edit. */
:root {
${unique([...curves, ...darkLogo]).join('\n')}
}
:root[data-theme='light'] {
${unique(lightLogo).join('\n')}
}
${hop.replace(/^ {2}/gm, '')}

${animations}
`,
);
// Their names for the start screen, read off the selectors (a page from file:// can't read rules).
const list = [...new Set([...animations.matchAll(/data-logo-anim='([a-z-]+)'/g)].map((m) => m[1]))];
writeFileSync(
  names,
  `// Generated by desktop/scripts/logo-css.mjs – do not edit.\nwindow.LOGO_ANIMATIONS = ${JSON.stringify(list)};\n`,
);
console.info(`wrote ${path.relative(desktop, target)}, ${list.length} animations`);
